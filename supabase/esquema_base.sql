-- Esquema base requerido por los demas scripts de supabase/ y por lib/.
-- Ejecutar este archivo primero en un proyecto Supabase nuevo.
-- No borra ni modifica datos existentes.
--
-- Compatibilidad con la aplicacion actual: esta usa la clave publica anon
-- para consultas y escrituras. Los permisos de abajo permiten ese uso, pero
-- no son apropiados para datos sensibles ni para un proyecto expuesto.

create table if not exists public.persona (
  identificacion text primary key,
  nombres text not null,
  password text not null,
  admin text not null default 'N',
  lectura text not null default ''
);

create table if not exists public.aspersiones (
  id bigint generated by default as identity primary key,
  bloque integer,
  bombero text,
  jefe_mipe text,
  semana integer,
  temperatura text,
  humedad_relativa text,
  tipo_aplicacion text,
  producto text,
  dosis text,
  cat_toxic text,
  grupo_fumigadores text,
  dias text,
  volumen_cama text,
  direccion text,
  num_camas text,
  equipo text,
  ire_horas text,
  usuario_registro text,
  blanco_biologico text,
  identificacion_registra text,
  firma_registra_base64 text,
  nombre_autoriza text,
  identificacion_autoriza text,
  firma_autoriza_base64 text,
  fecha date,
  fecha_registro timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.aseguramiento_plaguicidas (
  id bigint generated by default as identity primary key,
  semana integer,
  fecha date not null default current_date,
  nombre_producto text,
  proveedor text,
  formula_c text,
  cat_toxic text,
  presentacion text,
  total_unidades integer not null default 0,
  lote text,
  fecha_vencimiento text,
  estado_etiqueta text,
  estado_tapa text,
  sellos text,
  puntos_extraccion text,
  cumplimiento text,
  cantidad_cc_g integer not null default 0,
  color text,
  ph numeric,
  densidad double precision,
  observaciones text,
  autorizacion text,
  identificacion_asegura text,
  nombre_quien_asegura text,
  nombre_autoriza text,
  identificacion_autoriza text,
  firma_asegura_base64 text,
  firma_autoriza_base64 text
);

create table if not exists public.blancos_biologicos (
  id bigint generated by default as identity primary key,
  nombre text not null unique
);

create table if not exists public.equipos (
  id bigint generated by default as identity primary key,
  nombre text not null unique
);

create index if not exists aspersiones_bloque_fecha_registro_idx
  on public.aspersiones (bloque, fecha_registro desc);
create index if not exists aseguramiento_plaguicidas_fecha_idx
  on public.aseguramiento_plaguicidas (fecha desc);

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete
  on public.persona, public.aspersiones, public.aseguramiento_plaguicidas
  to anon, authenticated;
grant select on public.blancos_biologicos, public.equipos
  to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

